import SwiftUI

// MARK: - Language Manager
// Custom localization system — no .lproj files needed.
// All translations live in this file for easy maintenance.
// Use loc("key") anywhere, or Text(loc("key")) in SwiftUI.

@Observable
final class LanguageManager {

    static let shared = LanguageManager()

    enum Language: String, CaseIterable, Identifiable {
        case english    = "en"
        case indonesian = "id"

        var id: String { rawValue }

        var flag: String {
            switch self {
            case .english:    return "🇬🇧"
            case .indonesian: return "🇮🇩"
            }
        }

        var nativeName: String {
            switch self {
            case .english:    return "English"
            case .indonesian: return "Bahasa Indonesia"
            }
        }
    }

    var current: Language {
        didSet {
            UserDefaults.standard.set(current.rawValue, forKey: "dipo_language")
            Self.mirrorToAppGroup(current)
            // Cached formatters carry the OLD locale; keeping them would leave
            // dates in the previous language until the app restarted.
            DateFormatterCache.invalidate()
            // Bump trigger so RootView .id() forces a full re-render
            renderID = UUID()
        }
    }

    /// Changes whenever language switches — attach to RootView's .id() to force refresh.
    private(set) var renderID = UUID()

    /// Locale that follows the in-app language (not the iPhone system locale).
    /// Use this for DateFormatter / NumberFormatter so formatted output
    /// (e.g. "Thursday, 23 April 2026") matches the user's selected language
    /// instead of their iOS system setting.
    var currentLocale: Locale {
        switch current {
        case .english:    return Locale(identifier: "en_US")
        case .indonesian: return Locale(identifier: "id_ID")
        }
    }

    private init() {
        let saved = UserDefaults.standard.string(forKey: "dipo_language") ?? "en"
        self.current = Language(rawValue: saved) ?? .english
        // `didSet` does not run from init, and existing users never change the
        // setting again — write it once per launch so extensions can read it.
        Self.mirrorToAppGroup(current)
    }

    /// The share extension cannot see `UserDefaults.standard`; it reads the
    /// in-app language from the App Group so its sheet speaks the same language
    /// as the app rather than the phone's system language.
    private static func mirrorToAppGroup(_ language: Language) {
        UserDefaults(suiteName: "group.com.fahmiaquinas.DiPo")?.set(language.rawValue, forKey: "dipo_language")
    }

    // MARK: - Translation

    func t(_ key: String) -> String {
        let lang = translationOverride ?? current
        let table = lang == .indonesian ? translationsID : translationsEN
        return table[key] ?? key   // falls back to the key itself if not translated yet
    }

    /// Forces `t()` into a specific language without touching `current`.
    ///
    /// `@ObservationIgnored` on purpose: `current` has a `didSet` that persists
    /// the choice AND bumps `renderID`, which RootView uses as its `.id()` —
    /// flipping it would tear down and rebuild the entire UI, twice, mid-sync.
    /// This override changes nothing observable, so a view never sees it.
    @ObservationIgnored private var translationOverride: Language?

    /// Run `body` with every `loc()` inside it resolving in `language`.
    ///
    /// Exists so Web Sync can ship Smart Insights in BOTH languages. Those
    /// insights are assembled sentences with the user's own figures baked in
    /// ("Rp 7.394.500 spent against a Rp 5.000.000 budget"), so the web has no
    /// way to translate them after the fact — the only place both versions can
    /// be produced is here, where the engine and both string tables live.
    ///
    /// Synchronous and always restored, including on an early return.
    func withLanguage<T>(_ language: Language, _ body: () -> T) -> T {
        let previous = translationOverride
        translationOverride = language
        defer { translationOverride = previous }
        return body()
    }

